#!/usr/bin/env bash
# Set up the local dev stack in ~/stoat from the repo (docs/dev-environment.md section 10 and its appendix).
#
# Usage: tools/local/setup.sh [--dir <path>] [--force] [--start]
#   --dir <path>  set up there instead of ~/stoat. The tools only ever use ~/stoat, so this is for trying the script.
#   --force       go ahead although the folder exists: Stoat's files, the config from deploy/local/ and deploy/ are
#                 written again, in place. secrets.env and all data are kept. Revolt.toml's
#                 restrict_server_creation and host.env's ADMIN_USER_IDS go back to nobody until the next seed.
#   --start       then start the stack, deploy the client and the test page, seed, and make dev-admin the layer's
#                 admin. Only with ~/stoat, and with Docker running and nothing else on 127.0.0.1:80.
#
# Nothing from Stoat's repo is run: compose.yml and Caddyfile are copied from a scratch clone at a fixed commit.
# Secrets are generated here, as Stoat's generate_config.sh would, and never leave this machine.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
STOAT_REPO=https://github.com/stoatchat/self-hosted.git
STOAT_COMMIT=9af5e90
# LiveKit's key id, as in deploy/livekit.yml's webhook api_key.
LIVEKIT_KEY=2c2e5918ca20

dir="$HOME/stoat"
force=0
start=0
while [ $# -gt 0 ]; do
  case "$1" in
    --dir) dir="${2:?--dir needs a path}"; shift 2 ;;
    --force) force=1; shift ;;
    --start) start=1; shift ;;
    -h|--help) sed -n '2,13p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
    *) echo "unknown option: $1 (see --help)" >&2; exit 2 ;;
  esac
done
case "$dir" in /*) ;; *) dir="$PWD/$dir" ;; esac

die() { echo "setup: $*" >&2; exit 1; }
for cmd in git openssl rsync base64 node; do
  command -v "$cmd" >/dev/null || die "$cmd is missing (docs/dev-environment.md section 10)"
done
if [ "$start" = 1 ]; then
  [ "$dir" = "$HOME/stoat" ] || die "--start works only with ~/stoat, the folder the tools use"
  command -v docker >/dev/null || die "docker is missing"
  docker compose version >/dev/null 2>&1 || die "docker can't be reached, or has no compose plugin (is $USER in the docker group?)"
fi
if [ -e "$dir" ] && [ "$force" = 0 ]; then
  die "$dir exists; pass --force to write its config again (secrets and data are kept)"
fi
# concord-web and the guard run as uid 1000 and write to folders this user makes.
[ "$(id -u)" = 1000 ] || echo "setup: warning: uid $(id -u), not 1000: concord-web can't write concord/data until it is chowned to 1000" >&2

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

# Write a file in place with a fixed mode: compose bind-mounts single files such as Revolt.toml, and a replaced
# file would leave a running container reading the old one.
put() { # mode destination, content on stdin
  [ -e "$2" ] || install -m "$1" /dev/null "$2"
  chmod "$1" "$2"
  cat > "$2"
}

echo "setup: Stoat's compose.yml and Caddyfile at $STOAT_COMMIT"
git clone --quiet "$STOAT_REPO" "$tmp/self-hosted"
git -C "$tmp/self-hosted" -c advice.detachedHead=false checkout --quiet "$STOAT_COMMIT"
mkdir -p "$dir/concord"
for f in compose.yml Caddyfile; do put 0644 "$dir/$f" < "$tmp/self-hosted/$f"; done

echo "setup: config from deploy/local/"
put 0644 "$dir/.env" < "$ROOT/deploy/local/env.local"
put 0644 "$dir/.env.web" < "$ROOT/deploy/local/env.web.local"
put 0644 "$dir/stoat.json" < "$ROOT/deploy/local/stoat.local.json"
put 0644 "$dir/Revolt.toml" < "$ROOT/deploy/local/Revolt.local.toml"

# The secrets, generated once. The file key encrypts every upload, so an existing one is never replaced.
keys=(REVOLT__PUSHD__VAPID__PRIVATE_KEY REVOLT__PUSHD__VAPID__PUBLIC_KEY REVOLT__FILES__ENCRYPTION_KEY
  REVOLT__API__LIVEKIT__NODES__WORLDWIDE__SECRET REVOLT__API__LIVEKIT__NODES__WORLDWIDE__KEY)
if [ -f "$dir/secrets.env" ]; then
  echo "setup: keeping secrets.env"
  for k in "${keys[@]}"; do
    grep -q "^$k='.\+'$" "$dir/secrets.env" || die "secrets.env has no $k; add it, or move the file away to generate new secrets"
  done
else
  echo "setup: generating secrets.env"
  # The VAPID pair as generate_config.sh makes it: the PEM in base64, and the raw public point in base64url.
  openssl ecparam -name prime256v1 -genkey -noout -out "$tmp/vapid.pem" 2>/dev/null
  vapid_private="$(base64 -w0 < "$tmp/vapid.pem" | tr -d '=')"
  vapid_public="$(openssl ec -in "$tmp/vapid.pem" -outform DER 2>/dev/null | tail -c 65 | base64 -w0 | tr '/+' '_-' | tr -d '=')"
  put 0600 "$dir/secrets.env" <<EOF
# Secrets of this machine's local stack, generated by tools/local/setup.sh. Dev-only; never commit or copy them.
# The file key encrypts every upload: replacing it makes the stored files unreadable.
REVOLT__PUSHD__VAPID__PRIVATE_KEY='$vapid_private'
REVOLT__PUSHD__VAPID__PUBLIC_KEY='$vapid_public'
REVOLT__FILES__ENCRYPTION_KEY='$(openssl rand -base64 32)'
REVOLT__API__LIVEKIT__NODES__WORLDWIDE__SECRET='$(openssl rand -hex 24)'
REVOLT__API__LIVEKIT__NODES__WORLDWIDE__KEY='$LIVEKIT_KEY'
EOF
fi

echo "setup: deploy/ to concord/"
rsync -a --inplace --exclude web/ --exclude spike/ --exclude data/ --exclude local/ "$ROOT/deploy/" "$dir/concord/"
put 0644 "$dir/concord/host.env" < "$ROOT/deploy/local/host.env.local"
# LiveKit's side of the same key, always taken from secrets.env so the two can't disagree.
secret="$(sed -n "s/^REVOLT__API__LIVEKIT__NODES__WORLDWIDE__SECRET='\(.*\)'$/\1/p" "$dir/secrets.env")"
printf 'LIVEKIT_KEYS="%s: %s"\n' "$LIVEKIT_KEY" "$secret" | put 0600 "$dir/concord/livekit.env"
# The marker of a dev stack: dc adds Mailpit, and reset-data.sh may wipe.
touch "$dir/concord/.allow-wipe"
# The bind-mount folders, before the first start, or Docker makes them as root and later rsyncs fail.
mkdir -p "$dir/concord/web" "$dir/concord/spike"
install -d -m 0700 "$dir/concord/data" "$dir/concord/guard-data" "$dir/concord/spool/in"
install -d -m 0755 "$dir/concord/spool/out"
echo "setup: $dir is ready"

steps=(
  "$dir/concord/dc up -d"
  "pnpm deploy:stack"
  "pnpm deploy:web:dev"
  "pnpm deploy:spike:dev"
  "pnpm seed --reset"
  "pnpm seed account tuuli"
  "pnpm seed account onni"
)
if [ "$start" = 0 ]; then
  echo
  echo "Next, from the repo root ($ROOT), or run this again with --force --start:"
  for s in "${steps[@]}"; do echo "  $s"; done
  echo "  then put dev-admin's ID (tools/seed/.state.json) in $dir/concord/host.env's ADMIN_USER_IDS"
  echo "  and run $dir/concord/dc up -d concord-web"
  echo "Check with pnpm seed check, node tools/live/src/routes.ts and node tools/live/src/layer.ts."
  exit 0
fi

cd "$ROOT"
[ -d node_modules ] || pnpm install --frozen-lockfile
echo "setup: starting the stack"
"$dir/concord/dc" up -d
for _ in $(seq 90); do
  "$dir/concord/dc" exec -T caddy wget -qO /dev/null http://api:14702/ 2>/dev/null && break
  sleep 2
done
# deploy:stack also starts the account runner, which nothing else does on the local stack.
for s in "${steps[@]:1}"; do echo "setup: $s"; $s; done
admin="$(node -p 'require("./tools/seed/.state.json").personas["dev-admin"].userId')"
[[ "$admin" =~ ^[0-9A-HJKMNP-TV-Z]{26}$ ]] || die "no dev-admin ID in tools/seed/.state.json"
t="$(sed "s/^ADMIN_USER_IDS=.*/ADMIN_USER_IDS=$admin/" "$dir/concord/host.env")"
printf '%s\n' "$t" > "$dir/concord/host.env"
"$dir/concord/dc" up -d concord-web
echo "setup: done. dev-admin ($admin) is the layer's admin. Check with pnpm seed check."
